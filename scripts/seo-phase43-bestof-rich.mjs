function enrich(slug) {
  const cfg = RICH[slug];
  if (!cfg) return;
  const p = path.join(clientDir, slug, "index.html");
  if (!fs.existsSync(p)) { report.push(`[SKIP] /${slug}/ missing`); return; }
  let html = fs.readFileSync(p, "utf8");
  if (html.includes('data-rich="43"')) { report.push(`[SKIP] /${slug}/ already enriched`); return; }

  const faqHeading = "<h2>أسئلة شائعة</h2>";
  if (!html.includes(faqHeading)) { report.push(`[FAIL] /${slug}/ no FAQ heading`); return; }
  html = html.replace(faqHeading, `<div data-rich="43"></div>${cfg.analysis}${faqHeading}`);

  const blockMarker = '<div class="faq-block">';
  const startIdx = html.indexOf(blockMarker);
  if (startIdx > -1) {
    let depth = 0, i = startIdx, endIdx = -1;
    while (i < html.length) {
      if (html.startsWith("<div", i)) depth++;
      else if (html.startsWith("</div>", i)) { depth--; if (depth === 0) { endIdx = i + 6; break; } }
      i++;
    }
    if (endIdx > -1) {
      const extraHtml = cfg.faqExtra.map((q) => `<details><summary>${q.q}</summary><p>${q.a}</p></details>`).join("");
      html = html.slice(0, endIdx - 6) + extraHtml + html.slice(endIdx - 6);
    }
  }

  const faqLdMatch = html.match(/<script type="application\/ld\+json">(\{"@context":"https:\/\/schema.org","@type":"FAQPage"[\s\S]*?\})<\/script>/);
  if (faqLdMatch) {
    try {
      const faqObj = JSON.parse(faqLdMatch[1]);
      for (const q of cfg.faqExtra) {
        faqObj.mainEntity.push({ "@type": "Question", name: q.q, acceptedAnswer: { "@type": "Answer", text: q.a } });
      }
      html = html.replace(faqLdMatch[0], `<script type="application/ld+json">${JSON.stringify(faqObj)}</script>`);
    } catch (e) { report.push(`[WARN] /${slug}/ faq schema: ${e.message}`); }
  }

  const relItems = cfg.related.map((s) => `<li><a href="/${s}/">${RELATED_TITLES[s] || s}</a></li>`).join("");
  html = html.replace("</main>", `<section class="section"><div class="wrap"><h2>أدلة ذات صلة</h2><ul>${relItems}</ul></div></section></main>`);

  fs.writeFileSync(p, html, "utf8");
  report.push(`[OK] enriched /${slug}/`);
}

function main() {
  for (const slug of Object.keys(RICH)) enrich(slug);
  console.log("Phase 43 best-of enrichment done");
  console.log(report.join("\n"));
}

