const round1 = (n) => Math.round(n * 10) / 10;
const fmt = (n) => n.toFixed(1);
const siteLabel = (url) => (url || "").replace(/^https?:\/\/(www\.)?/, "").replace(/\/.*$/, "");

function enrich(d) {
  const [delivery, management, finance, transparency, density] = d.scores;
  const total = round1((delivery + management + finance + transparency + density) / 5);
  const site = d.domain
    ? `<a href="${d.domain}" target="_blank" rel="nofollow noopener">${siteLabel(d.domain)}</a> — ${d.reviewed}`
    : `${d.sourceNote} — ${d.reviewed}`;
  return { ...d, delivery, management, finance, transparency, density, total, totalLabel: fmt(total), source: site, profile: true };
}

