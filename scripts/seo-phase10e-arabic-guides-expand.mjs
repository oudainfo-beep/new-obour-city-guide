function readFile(p) {
  return fs.readFileSync(p, "utf8");
}

function writeFile(p, content) {
  fs.writeFileSync(p, content);
}

function countArabicWordsInMain(html) {
  const mainMatch = html.match(/<main[^>]*>([\s\S]*?)<\/main>/i);
  if (!mainMatch) return 0;
  const text = mainMatch[1]
    .replace(/<[^>]+>/g, " ")
    .replace(/[^\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF\uFB50-\uFDFF\uFE70-\uFEFF\s]+/g, " ");
  const words = text.split(/\s+/).filter((w) => {
    if (!w) return false;
    return /[\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF\uFB50-\uFDFF\uFE70-\uFEFF]/.test(w);
  });
  return words.length;
}

function injectBeforeMainEnd(html, marker, sectionHtml) {
  if (html.includes(marker)) return { changed: false, reason: "marker" };
  const mainEnd = html.lastIndexOf("</main>");
  if (mainEnd === -1) return { changed: false, reason: "no-main" };
  const insert = `\n${marker}\n${sectionHtml}\n`;
  const newHtml = html.slice(0, mainEnd) + insert + html.slice(mainEnd);
  return { changed: true, html: newHtml };
}

