const TARGETS = [
  {
    slug: "dining-guide",
    file: path.join(clientDir, "dining-guide", "index.html"),
    marker: DINING_MARKER,
    section: DINING_SECTION,
  },
  {
    slug: "shopping-guide",
    file: path.join(clientDir, "shopping-guide", "index.html"),
    marker: SHOPPING_MARKER,
    section: SHOPPING_SECTION,
  },
  {
    slug: "health-guide",
    file: path.join(clientDir, "health-guide", "index.html"),
    marker: HEALTH_MARKER,
    section: HEALTH_SECTION,
  },
];

function main() {
  console.log("=== المرحلة 10e: توسيع أدلة الأكل والتسوق والصحة ===");

  for (const t of TARGETS) {
    if (!fs.existsSync(t.file)) {
      rep(t.slug, "الملف غير موجود: " + t.file);
      continue;
    }

    const html = readFile(t.file);
    const before = countArabicWordsInMain(html);

    if (html.includes(t.marker)) {
      const after = countArabicWordsInMain(html);
      rep(t.slug, `تُخطّى (marker موجود). كلمات داخل <main>: ${before}`);
      continue;
    }

    const r = injectBeforeMainEnd(html, t.marker, t.section);
    if (!r.changed) {
      rep(t.slug, `فشل الحقن: ${r.reason}`);
      continue;
    }

    writeFile(t.file, r.html);
    const after = countArabicWordsInMain(r.html);
    rep(t.slug, `تم الحقن. كلمات داخل <main>: ${before} ← ${after} (+${after - before})`);
  }

  console.log("=== تقرير المرحلة 10e ===");
  for (const line of report) console.log(line);
  console.log("=== انتهت المرحلة 10e ===");
}

main();
