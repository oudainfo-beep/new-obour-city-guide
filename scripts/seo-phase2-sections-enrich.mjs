function extractDistrict(addr) {
  if (!addr || addr === "—") return "غير محدد";
  const a = addr.toLowerCase();

  const patterns = [
    ["الحي الأول", /(?:الحي\s+الأول|1st\s+district|first\s+district|حي\s+المجد)/i],
    ["الحي الثاني", /(?:الحي\s+الثاني|2nd\s+district|second\s+district)/i],
    ["الحي الثالث", /(?:الحي\s+الثالث|3rd\s+district|third\s+district)/i],
    ["الحي الرابع", /(?:الحي\s+الرابع|4th\s+district|fourth\s+district)/i],
    ["الحي الخامس", /(?:الحي\s+الخامس|5th\s+district|fifth\s+district)/i],
    ["الحي السادس", /(?:الحي\s+السادس|6th\s+district|sixth\s+district)/i],
    ["الحي السابع", /(?:الحي\s+السابع|7th\s+district|seventh\s+district)/i],
    ["الحي الثامن", /(?:الحي\s+الثامن|8th\s+district|eighth\s+district)/i],
    ["الحي التاسع", /(?:الحي\s+التاسع|9th\s+district|ninth\s+district)/i],
    ["حي الشباب / إسكان الشباب", /(?:حي\s+الشباب|إسكان\s+الشباب|youth\s+district|youth\s+housing|youth\s+street|إسكان\s+شباب)/i],
    ["جولف سيتي", /(?:جولف\s+سيتي|golf\s+city|golf\s+obour)/i],
    ["المنطقة الصناعية", /(?:المنطقة\s+الصناعية|industrial\s+zone)/i],
    ["جمعية أحمد عرابي", /(?:جمعية\s+أحمد\s+عرابي|ahmed\s+orabi|أحمد\s+عرابي)/i],
    ["بندر العبور", /(?:بندر\s+العبور|bandar\s+el\s+obour)/i],
    ["العبور الجديدة", /(?:العبور\s+الجديدة|new\s+obour)/i],
  ];

  for (const [name, re] of patterns) {
    if (re.test(a)) return name;
  }
  if (/مدينة\s+العبور/.test(a)) return "العبور (عام)";
  return "خارج نطاق العبور";
}

function computeDistribution(items) {
  const counts = {};
  for (const item of items) {
    const d = extractDistrict(item.a);
    counts[d] = (counts[d] || 0) + 1;
  }
  const total = items.length || 1;
  const rows = Object.entries(counts)
    .map(([district, count]) => ({ district, count, pct: ((count / total) * 100).toFixed(1) }))
    .sort((a, b) => b.count - a.count);

  // اجمع النسب الصغيرة (>8 صفوف) تحت "أخرى"
  if (rows.length > 8) {
    const top = rows.slice(0, 7);
    const rest = rows.slice(7);
    const restCount = rest.reduce((s, r) => s + r.count, 0);
    const restPct = ((restCount / total) * 100).toFixed(1);
    return [...top, { district: "أخرى", count: restCount, pct: restPct }];
  }
  return rows;
}

function distributionTable(rows, total) {
  const thead = `<thead><tr><th>المنطقة</th><th>العدد</th><th>النسبة</th></tr></thead>`;
  const tbody = rows.map((r) => `<tr><td>${r.district}</td><td>${r.count}</td><td>${r.pct}%</td></tr>`).join("");
  return `<div class="responsive-table"><table>${thead}<tbody>${tbody}</tbody></table></div><p class="table-note">الإجمالي: ${total} مدخل. التوزيع مُستخرج برمجيًا من حقل العنوان في البيانات المنشورة.</p>`;
}

