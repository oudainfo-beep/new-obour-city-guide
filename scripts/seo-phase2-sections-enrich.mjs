function buildBlock(slug, data) {
  const copy = COPY[slug];
  if (!copy) return null;

  const items = data.items || [];
  const rows = computeDistribution(items);
  const total = items.length;

  const faqSchema = {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    "mainEntity": copy.faq.map(([q, a]) => ({
      "@type": "Question",
      "name": q,
      "acceptedAnswer": { "@type": "Answer", "text": a },
    })),
  };

  const faqHtml = copy.faq
    .map(([q, a]) => `<details><summary>${q}</summary><p>${a}</p></details>`)
    .join("");

  const html = `
${MARKER}
<section class="phase2-6-enrich wrap" aria-label="معلومات إضافية عن الدليل">
  <h2>نظرة عامة على ${data.title}</h2>
  ${copy.intro}
  <h2>التوزيع الجغرافي حسب الحي</h2>
  <p>الجدول التالي يُحسب برمجيًا من عناوين المنشورات المسجلة في الدليل. الهدف ليس تعدادًا كاملًا، بل إعطاؤك فكرة عن كثافة الخدمة في كل منطقة.</p>
  ${distributionTable(rows, total)}
  <h2>أسئلة شائعة</h2>
  <div class="faq-group">
    ${faqHtml}
  </div>
</section>
`;

  return { html, faqSchema };
}

function injectPage(slug, { html, faqSchema }) {
  const pagePath = path.join(clientDir, slug, "index.html");
  if (!fs.existsSync(pagePath)) {
    rep("skip", `${slug}/: الصفحة غير موجودة`);
    return false;
  }

  let content = fs.readFileSync(pagePath, "utf8");
  if (content.includes(MARKER)) {
    rep("skip", `${slug}/: مُثرى سابقًا`);
    return false;
  }

  // حقن المحتوى قبل </main>
  content = content.replace("</main>", `${html}\n</main>`);

  // حقن FAQ schema قبل </head>
  const schemaTag = `<script type="application/ld+json">${JSON.stringify(faqSchema)}</script>`;
  content = content.replace("</head>", `${schemaTag}\n</head>`);

  fs.writeFileSync(pagePath, content, "utf8");
  rep("enrich", `${slug}/: أُضيفت مقدمة + جدول توزيع + FAQ (${faqSchema.mainEntity.length} سؤال)`);
  return true;
}

// ---------------------------------------------------------------------------
// التنفيذ
// ---------------------------------------------------------------------------
let done = 0;
for (const { slug, file } of TARGETS) {
  const jsonPath = path.join(dataDir, file);
  if (!fs.existsSync(jsonPath)) {
    rep("skip", `${slug}/: ملف JSON غير موجود (${file})`);
    continue;
  }
  const data = JSON.parse(fs.readFileSync(jsonPath, "utf8"));
  const block = buildBlock(slug, data);
  if (!block) {
    rep("skip", `${slug}/: لا يوجد نص جاهز`);
    continue;
  }
  if (injectPage(slug, block)) done++;
}

console.log("=== تقرير المرحلة الثانية: إثراء الأدلة (2.6) ===");
for (const r of report) console.log(r);
console.log(`=== انتهى: ${done} أدلّة مُثراة ===`);
process.exit(report.some((r) => r.startsWith("[skip]")) ? 0 : 0);
