function expandPage(slug, expansion, minWords, marker) {
  const file = path.join(clientDir, slug, "index.html");
  const html = fs.readFileSync(file, "utf8");

  if (html.includes(marker)) {
    rep("skip", `/${slug}/: التوسعة ${marker} موجودة بالفعل`);
    return;
  }

  const next = injectBeforeAside(html, expansion, marker);
  fs.writeFileSync(file, next);

  // عدّ كلمات النص داخل المقال بعد الحقن
  const articleMatch = next.match(/<article>(.*?)<\/article>/s);
  const articleText = articleMatch ? articleMatch[1].replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim() : "";
  const wordCount = articleText.split(/\s+/).length;
  rep("expand", `/${slug}/: أُضيفت توسعة ${marker} — كلمات المقال ${wordCount} (هدف ${minWords}+)`);
}

