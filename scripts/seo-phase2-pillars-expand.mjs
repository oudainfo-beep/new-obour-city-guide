function injectBeforeAside(html, payload, marker) {
  if (html.includes(marker)) return html;
  const target = "</article><aside class=\"action-card\">";
  if (!html.includes(target)) {
    throw new Error("لم يُعثر على نقطة الحقن المعتادة (</article><aside class=action-card>)");
  }
  return html.replace(target, `${marker}${payload}</article><aside class="action-card">`);
}

