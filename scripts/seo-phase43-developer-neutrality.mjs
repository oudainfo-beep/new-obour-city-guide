const OLD_GAP = "لا ينشر أي مطوّر في المدينتين — بما فيهم عوده — عقدًا نموذجيًا";
const NEW_GAP = "لا ينشر أي مطوّر في المدينتين عقدًا نموذجيًا";

const TARGETS = [
  { file: "developers/index.html", pairs: [[OLD1, NEW1], [OLD_META, NEW_META], [OLD_OUDA, NEW_OUDA], [OLD_VAL, NEW_VAL]] },
  ...["ouda", "alashraaf", "alsafwa", "elmoltqa", "kayan", "valero"].map(s => ({
    file: `developers/${s}/index.html`, pairs: [[OLD_GAP, NEW_GAP]],
  })),
];

let changed = 0;
for (const t of TARGETS) {
  const p = path.join(clientDir, t.file);
  if (!fs.existsSync(p)) { console.warn(`[phase43] skip (missing): ${t.file}`); continue; }
  let html = fs.readFileSync(p, "utf8");
  let n = 0;
  for (const [oldStr, newStr] of t.pairs) {
    const c = html.split(oldStr).length - 1;
    if (c === 0) { console.warn(`[phase43] not found in ${t.file}: ${oldStr.slice(0, 40)}…`); continue; }
    html = html.split(oldStr).join(newStr);
    n += c;
  }
  if (n > 0) { fs.writeFileSync(p, html); changed += n; console.log(`[phase43] ${t.file}: ${n} replacement(s)`); }
}
console.log(`[phase43] developer-neutrality done — total replacements: ${changed}`);
